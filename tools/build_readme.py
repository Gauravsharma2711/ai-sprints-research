"""Render README.md from README.template.md with the tools/build_paper.py placeholder engine.

Every number in the README comes from a placeholder resolved against results/tables/*.csv,
config.yaml or the benchmark files, exactly as in the paper (see tools/build_paper.py for the
placeholder syntax). Placeholders may appear only inside generated blocks:

    <!-- BEGIN GENERATED: <name> -->
    ... text with {{num:...}}, {{ci:...}}, {{table:...}}, {{cfg:...}} ... placeholders ...
    <!-- END GENERATED: <name> -->

The markers are kept in README.md so a reader can see which parts are generated. Text outside the
blocks is copied verbatim (template notes ``<!-- TEMPLATE: ... -->`` are dropped). Two README-only
placeholders are resolved before the engine runs:

    {{readme:paper_title}}                   the first ``# `` heading of paper/draft.md
    {{readme:ci_zero:<table>:<filters>}}     a verdict phrase for a row without a predicted sign,
                                             computed from that row's ci_low/ci_high:
                                             "inconclusive (CI includes 0)", "CI excludes 0, positive"
                                             or "CI excludes 0, negative"

Any placeholder that cannot be resolved, or any placeholder outside a generated block, is an error:
the build exits 1 and writes nothing.

Usage (from the repo root):
    python tools/build_readme.py            # write README.md
    python tools/build_readme.py --check    # exit 1 if README.md differs from a fresh render
"""

from __future__ import annotations

import argparse
import difflib
import re
import sys
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from tools.build_paper import COMMENT_RE, BuildContext, _resolve, fill, load_config  # noqa: E402

BLOCK_RE = re.compile(
    r"^<!-- BEGIN GENERATED: (?P<name>[\w.-]+) -->[ \t]*\n(?P<body>.*?)\n?"
    r"^<!-- END GENERATED: (?P=name) -->[ \t]*$",
    re.DOTALL | re.MULTILINE,
)
MARKER_RE = re.compile(r"<!-- (?:BEGIN|END) GENERATED:")
TEMPLATE_NOTE_RE = re.compile(r"<!-- TEMPLATE:.*?-->[ \t]*\n?", re.DOTALL)
README_PH_RE = re.compile(r"\{\{\s*readme:(?P<key>[\w-]+)\s*\}\}")
CI_ZERO_RE = re.compile(r"\{\{\s*readme:ci_zero:(?P<table>[^:{}\n]+):(?P<filters>[^:{}\n]*?)\s*\}\}")
HEADER = ("<!-- This file is generated by tools/build_readme.py from README.template.md. "
          "Edit the template, then run: python tools/build_readme.py -->\n\n")


class ReadmeError(Exception):
    """The template could not be rendered."""


@dataclass(frozen=True)
class Segment:
    name: str | None   # None = static text
    text: str


def split_template(template: str) -> list[Segment]:
    """Split the template into static text and named generated blocks."""
    segments: list[Segment] = []
    pos = 0
    names: set[str] = set()
    for m in BLOCK_RE.finditer(template):
        segments.append(Segment(None, template[pos:m.start()]))
        name = m.group("name")
        if name in names:
            raise ReadmeError(f"generated block {name!r} appears twice")
        names.add(name)
        segments.append(Segment(name, m.group("body")))
        pos = m.end()
    segments.append(Segment(None, template[pos:]))
    for seg in segments:
        if seg.name is None and MARKER_RE.search(seg.text):
            raise ReadmeError("unmatched or malformed BEGIN/END GENERATED marker in the template")
    return segments


def paper_title(draft_path: Path) -> str:
    if not draft_path.is_file():
        raise ReadmeError(f"paper draft not found at {draft_path}")
    text = COMMENT_RE.sub("", draft_path.read_text(encoding="utf-8"))
    for line in text.splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    raise ReadmeError(f"no '# ' title heading in {draft_path}")


def ci_zero_phrase(ctx: BuildContext, table: str, filters: str) -> str:
    """Verdict phrase from one row's CI; raises ReadmeError if the row or its CI is missing."""
    bounds: list[float] = []
    for col in ("ci_low", "ci_high"):
        filled, errs = fill(ctx, f"{{{{num:{table}:{filters}:{col}:s}}}}")
        if errs:
            raise ReadmeError("; ".join(errs))
        try:
            value = float(filled)
        except ValueError as exc:
            raise ReadmeError(f"{col} is not a number: {filled!r}") from exc
        if value != value:   # NaN
            raise ReadmeError(f"{col} is missing (NaN)")
        bounds.append(value)
    lo, hi = bounds
    if lo > 0:
        return "CI excludes 0, positive"
    if hi < 0:
        return "CI excludes 0, negative"
    return "inconclusive (CI includes 0)"


def render(ctx: BuildContext, template: str, draft_path: Path) -> tuple[str, list[str]]:
    """Render the template. Returns (text, errors); the text is meaningless if errors is non-empty."""
    errors: list[str] = []
    try:
        segments = split_template(template)
    except ReadmeError as exc:
        return "", [str(exc)]
    readme_values: dict[str, str] = {}

    def readme_ph(m: re.Match[str]) -> str:
        key = m.group("key")
        if key not in readme_values:
            if key != "paper_title":
                errors.append(f"{m.group(0)}: unknown README placeholder (known: paper_title, ci_zero)")
                return m.group(0)
            try:
                readme_values[key] = paper_title(draft_path)
            except ReadmeError as exc:
                errors.append(f"{m.group(0)}: {exc}")
                return m.group(0)
        return readme_values[key]

    out: list[str] = [HEADER]
    for seg in segments:
        if seg.name is None:
            static = TEMPLATE_NOTE_RE.sub("", seg.text)
            if "{{" in static or "}}" in static:
                line = next(ln for ln in static.splitlines() if "{{" in ln or "}}" in ln)
                errors.append(f"placeholder outside a generated block: {line.strip()[:120]}")
            out.append(static)
            continue
        def ci_zero_ph(m: re.Match[str]) -> str:
            try:
                return ci_zero_phrase(ctx, m.group("table").strip(), m.group("filters").strip())
            except ReadmeError as exc:
                errors.append(f"{m.group(0)}: {exc}")
                return m.group(0)

        body = CI_ZERO_RE.sub(ci_zero_ph, seg.text)
        body = README_PH_RE.sub(readme_ph, body)
        filled, block_errors = fill(ctx, body)
        errors.extend(f"[{seg.name}] {e}" for e in block_errors)
        out.append(f"<!-- BEGIN GENERATED: {seg.name} -->\n{filled.rstrip()}\n<!-- END GENERATED: {seg.name} -->")
    text = "".join(out)
    text = re.sub(r"\n{3,}", "\n\n", text).strip() + "\n"
    return text, errors


def _normalise(text: str) -> str:
    return text.replace("\r\n", "\n")


def main(argv: Sequence[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--template", type=Path, default=REPO_ROOT / "README.template.md")
    ap.add_argument("--out", type=Path, default=REPO_ROOT / "README.md")
    ap.add_argument("--config", type=Path, default=REPO_ROOT / "config.yaml")
    ap.add_argument("--draft", type=Path, default=REPO_ROOT / "paper" / "draft.md",
                    help="source of {{readme:paper_title}}")
    ap.add_argument("--tables", type=Path, default=None, help="default: paths.tables in config.yaml")
    ap.add_argument("--figures", type=Path, default=None, help="default: paths.figures in config.yaml")
    ap.add_argument("--check", action="store_true", help="exit 1 if --out differs from a fresh render")
    ap.add_argument("--allow-dry-run", action="store_true", help="accept rows whose data_source is dry-run")
    args = ap.parse_args(argv)

    cfg = load_config(args.config)
    ctx = BuildContext(
        tables_dir=args.tables or _resolve(args.config, cfg["paths"]["tables"]),
        figures_dir=args.figures or _resolve(args.config, cfg["paths"]["figures"]),
        config_path=args.config, draft_dir=args.template.resolve().parent,
        out_dir=args.out.resolve().parent, allow_dry_run=args.allow_dry_run,
    )
    if not args.template.is_file():
        print(f"BUILD FAILED: template not found at {args.template}", file=sys.stderr)
        return 1
    text, errors = render(ctx, args.template.read_text(encoding="utf-8"), args.draft)
    for w in ctx.warnings:
        print(f"WARNING: {w}", file=sys.stderr)
    if errors:
        print(f"BUILD FAILED: {len(errors)} error(s); {args.out} not written.", file=sys.stderr)
        for e in errors:
            print(f"  {e}", file=sys.stderr)
        return 1

    if args.check:
        current = _normalise(args.out.read_text(encoding="utf-8")) if args.out.is_file() else ""
        if current == text:
            print(f"{args.out} is up to date")
            return 0
        diff = list(difflib.unified_diff(current.splitlines(), text.splitlines(),
                                         fromfile=str(args.out), tofile="fresh render", lineterm="", n=1))
        print(f"{args.out} is out of date; run: python tools/build_readme.py", file=sys.stderr)
        for line in diff[:40]:
            print(line, file=sys.stderr)
        return 1

    with args.out.open("w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print(f"wrote {args.out} ({len(ctx.used)} generated values)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
