"""Export every fixed prompt, verbatim, to paper/appendix_prompts.md (Appendix A of the paper).

Sources: src/prompts.py (system prompts for each condition, probe instruction, re-ask messages,
ablation placeholders, judge prompt) and the turns file named in config.yaml (all paraphrases).
Nothing is retyped: the text is read from the code and data, so the appendix cannot drift.

Usage (from the repo root):
    python tools/export_prompts.py            # write paper/appendix_prompts.md
    python tools/export_prompts.py --check    # exit 1 if the committed file is out of date
"""

from __future__ import annotations

import argparse
import sys
from collections.abc import Sequence
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from src import prompts  # noqa: E402

DEFAULT_OUT = REPO_ROOT / "paper" / "appendix_prompts.md"
TURN_KIND_NOTES: dict[str, str] = {
    "bluff": "Turn 2 in arm T2A and the T3 arms: a senior person disagrees and offers no data.",
    "release": "Final turn of T3, T3a and T3b: the objection is withdrawn and a fresh assessment requested.",
    "release_no_bluff": "Final turn of T3c (bluff exchange removed); paraphrase i pairs with release paraphrase i.",
    "neutral": "Turn 2 of T2N and both follow-up turns of T3N: a content-free request to restate.",
}


def fence(text: str) -> str:
    ticks = "````" if "```" in text else "```"
    return f"{ticks}text\n{text}\n{ticks}"


def render(turns_path: Path) -> str:
    with turns_path.open(encoding="utf-8") as fh:
        turns = yaml.safe_load(fh)
    out: list[str] = [
        "<!-- Generated by tools/export_prompts.py from src/prompts.py and "
        f"{turns_path.name}. Do not edit by hand. -->",
        "",
        "Every fixed prompt used in the experiment, reproduced verbatim from the code. "
        "Text in braces is filled per call: `{claim}` is the item's question, `{prose}` the stripped "
        "briefing, `{c1:.2f}` the model's own Turn-1 probability. Item-specific evidence turns are "
        "in `data/benchmark/items.jsonl`.",
        "",
        "### A.1 System prompts (one per condition)",
        "",
    ]
    for cond in prompts.CONDITIONS:
        out += [f"**{cond}**", "", fence(prompts.system_prompt(cond)), ""]
    out += [
        "### A.2 Logit probe (user turn; the system prompt is the condition's own)",
        "",
        fence(prompts.probe_user_message("{claim}")),
        "",
        "### A.3 Re-ask messages (one re-ask after a parse failure)",
        "",
        "**Subject re-ask**", "", fence(prompts.REASK_MESSAGE), "",
        "**Judge re-ask**", "", fence(prompts.JUDGE_REASK_MESSAGE), "",
        "### A.4 Context-ablation placeholders (replace the model's own T2A reply)",
        "",
        "**T3a: neutral placeholder**", "", fence(prompts.NEUTRAL_PLACEHOLDER), "",
        "**T3b: stand-firm reply restating c1**", "", fence(prompts._STAND_FIRM_TEMPLATE), "",
        "### A.5 Judge prompt",
        "",
        "**System**", "", fence(prompts.JUDGE_SYSTEM), "",
        "**User**", "", fence(prompts.judge_messages("{claim}", "{prose}")[1]["content"]), "",
        "### A.6 Fixed user turns (all paraphrases)",
        "",
    ]
    for kind, paraphrases in turns.items():
        out += [f"**{kind}**" + (f": {TURN_KIND_NOTES[kind]}" if kind in TURN_KIND_NOTES else ""), ""]
        for i, text in enumerate(paraphrases):
            out += [f"Paraphrase {i}:", "", fence(str(text)), ""]
    return "\n".join(out).rstrip("\n") + "\n"


def default_turns_path() -> Path:
    with (REPO_ROOT / "config.yaml").open(encoding="utf-8") as fh:
        cfg = yaml.safe_load(fh)
    return REPO_ROOT / cfg["paths"]["turns"]


def main(argv: Sequence[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--turns", type=Path, default=None, help="default: paths.turns in config.yaml")
    ap.add_argument("--check", action="store_true", help="exit 1 if --out differs from a fresh export")
    args = ap.parse_args(argv)
    text = render(args.turns or default_turns_path())
    if args.check:
        current = args.out.read_text(encoding="utf-8") if args.out.is_file() else ""
        if current != text:
            print(f"{args.out} is out of date; run tools/export_prompts.py", file=sys.stderr)
            return 1
        print(f"{args.out} is up to date")
        return 0
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
