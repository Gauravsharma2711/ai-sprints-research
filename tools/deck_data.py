"""Collect every number shown in the slide deck from generated tables, config and benchmark files.

Writes one JSON file that tools/build_deck.js turns into slides/deck.pptx. Nothing is typed by hand:
results come from results/tables/*.csv (generated by src/analyze.py from results/raw/), design facts
from the benchmark files and config.yaml, engineering facts from the test suite and tools/gates.py.

    python tools/deck_data.py --out temp/deck/deck_data.json
"""

from __future__ import annotations

import argparse
import json
import math
import subprocess
import sys
from pathlib import Path
from typing import Any

import pandas as pd
import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tools"))

import build_paper as bp  # noqa: E402
import gates  # noqa: E402

TABLES = ROOT / "results" / "tables"
POOLED = "ALL_MODELS"
SUBJECTS = ["qwen2.5-7b", "phi-3.5-mini", "mistral-7b"]
CONDITIONS = ["default", "stand_firm", "contract_prompt"]


def _f(x: Any) -> float | None:
    try:
        v = float(x)
    except (TypeError, ValueError):
        return None
    return None if math.isnan(v) else v


def _one(df: pd.DataFrame, **filters: Any) -> pd.Series:
    sub = df
    for k, v in filters.items():
        sub = sub[sub[k].astype(str) == str(v)]
    if len(sub) != 1:
        raise SystemExit(f"expected 1 row for {filters}, got {len(sub)}")
    return sub.iloc[0]


def _est(row: pd.Series) -> dict[str, Any]:
    out: dict[str, Any] = {"est": _f(row["estimate"]), "lo": _f(row["ci_low"]), "hi": _f(row["ci_high"])}
    for col in ("verdict", "holm_p", "holm_verdict", "n_items", "n_cells"):
        if col in row.index:
            val = row[col]
            out[col] = _f(val) if col in ("holm_p", "n_items", "n_cells") else (None if pd.isna(val) else str(val))
    return out


def count_tests() -> int:
    out = subprocess.run([sys.executable, "-m", "pytest", "--collect-only", "-q"], cwd=ROOT,
                         capture_output=True, text=True, check=True).stdout
    return sum(1 for line in out.splitlines() if "::" in line)


def collect() -> dict[str, Any]:
    cfg_path = ROOT / "config.yaml"
    cfg = bp.load_config(cfg_path)
    facts = bp.data_facts(cfg_path)
    hyp = pd.read_csv(TABLES / "hypotheses.csv")
    met = pd.read_csv(TABLES / "metrics.csv")
    con = pd.read_csv(TABLES / "condition_contrasts.csv")
    cov = pd.read_csv(TABLES / "coverage.csv")
    para = pd.read_csv(TABLES / "per_paraphrase.csv")
    first = pd.read_csv(TABLES / "hypotheses_first_attempt.csv")
    allsamp = pd.read_csv(TABLES / "robustness" / "all_samples" / "hypotheses.csv")
    refs = bp.parse_references((ROOT / "paper" / "references.md").read_text(encoding="utf-8"))
    cited = bp.cited_keys((ROOT / "paper" / "draft.md").read_text(encoding="utf-8"))

    def h(hid: str, subject: str = POOLED, metric: str | None = None, frame: pd.DataFrame = hyp) -> dict[str, Any]:
        f: dict[str, Any] = {"hypothesis": hid, "subject": subject}
        if metric:
            f["metric"] = metric
        return _est(_one(frame, **f))

    def m(metric: str, condition: str = "default", subject: str = POOLED) -> dict[str, Any]:
        return _est(_one(met, subject=subject, condition=condition, tier="all", metric=metric))

    pooled_hyp = hyp[hyp["subject"] == POOLED]
    data: dict[str, Any] = {
        "facts": facts,
        "design": {
            "n_models": int(cov["subject"].nunique()),
            "n_cells": int(cov["n_cells"].sum()),
            "n_judged": int(cov.loc[cov["sample"] == 0, "n_judged"].sum()),
            "bootstrap": int(cfg["analysis"]["bootstrap_resamples"]),
            "ci_level": float(cfg["analysis"]["ci_level"]),
            "judge_model": str(cfg["judge"]["model"]),
            "samples": {s: int(cov.loc[cov["subject"] == s, "sample"].nunique()) for s in SUBJECTS},
        },
        "headline": {
            "H2": h("H2"), "H4": h("H4"),
            "T3a": h("H5", metric="ablation_T3a_minus_T3"),
            "T3b": h("H5", metric="ablation_T3b_minus_T3"),
            "T3c": h("H5", metric="ablation_T3c_minus_T3"),
            "H3_bluff": h("H3", metric="bluff_shift"), "H3_evidence": h("H3", metric="evidence_update"),
            "H6_excess": h("H6", metric="excess_hysteresis_abs"), "H6_selectivity": h("H6", metric="selectivity"),
            "H1": h("H1"),
            "selectivity_default": m("selectivity"),
            "recovery_pooled": m("recovery_fraction"),
            "evidence_default": m("evidence_update"),
            "neutral_default": m("neutral_shift_T2N"),
            "bluff_default": m("bluff_shift"),
            "contract_hysteresis_abs": _est(_one(con, subject=POOLED, contrast="contract_prompt - default",
                                                 tier="all", metric="hysteresis_abs")),
        },
        "n_pooled_tests": int(len(pooled_hyp)),
        "n_supported_holm": int((pooled_hyp["holm_verdict"] == "supported").sum()),
        "per_model": {s: {"H2": h("H2", s), "H4": h("H4", s), "T3a": h("H5", s, "ablation_T3a_minus_T3"),
                          "recovery": m("recovery_fraction", subject=s)} for s in SUBJECTS},
        "by_condition": {c: {k: m(k, c) for k in ("bluff_shift", "neutral_shift_T2N", "evidence_update",
                                                    "excess_hysteresis_abs", "selectivity")}
                         for c in CONDITIONS},
        "paraphrase": {str(k): {mt: _est(_one(para, subject=POOLED, condition="default", paraphrase_idx=k,
                                              metric=mt))
                                for mt in ("net_bluff_shift", "excess_hysteresis_abs", "ablation_T3a_minus_T3")}
                       for k in sorted(para["paraphrase_idx"].unique())},
        "first_attempt_T3a": h("H5", metric="ablation_T3a_minus_T3", frame=first),
        "all_samples_H2": h("H2", frame=allsamp),
        "all_samples_verdicts_match": bool(
            (allsamp[allsamp["subject"] == POOLED].set_index(["hypothesis", "metric"])["verdict"]
             == pooled_hyp.set_index(["hypothesis", "metric"])["verdict"]).all()),
        "turns_p0": {k: v[0] for k, v in yaml.safe_load(
            (ROOT / cfg["paths"]["turns"]).read_text(encoding="utf-8")).items()},
        "example_item": next(it for it in (json.loads(line) for line in
                                           (ROOT / cfg["paths"]["benchmark"]).read_text(encoding="utf-8")
                                           .splitlines() if line.strip()) if it["id"] == "EH002"),
        "n_briefings": int(len(pd.read_csv(TABLES / "human_rating_sheet.csv"))),
        "engineering": {
            "tests": count_tests(),
            "gates": len(gates.GATES),
            "n_refs_cited": len(cited),
            "n_refs_confirmed": sum(1 for k in cited if k in refs and refs[k].confirmed),
            "raw_log_files": len(list((ROOT / "results" / "raw" / "trajectories").glob("*.jsonl"))),
        },
    }
    return data


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(collect(), indent=2), encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
